def get(base, path):
    try:
        with urllib.request.urlopen(f"http://{base}{path}", timeout=8) as r:
            return r.status, json.loads(r.read().decode())
    except urllib.error.HTTPError as e:
        return e.code, None
    except Exception as e:                                   # noqa: BLE001
        return 0, {"_error": str(e)}


def wait_for(base, src, field, expect, timeout=3.0):
    """Poll until `field` reads `expect`, or give up. Returns (value, seconds)."""
    import time
    t0 = time.time()
    actual = None
    while time.time() - t0 < timeout:
        _, body = get(base, src)
        actual = (body or {}).get(field)
        if actual == expect:
            return actual, time.time() - t0
        time.sleep(0.1)
    return actual, time.time() - t0


def require_simulator(base):
    status, body = get(base, "/api/backend")
    if status != 200 or not isinstance(body, dict) or body.get("simulated") is not True:
        sys.exit(
            f"REFUSING to walk {base}.\n"
            f"  /api/backend -> {status} {body}\n"
            "  This tool fires state-changing routes (PTT, mode, antenna). It runs\n"
            "  only against a host that proves simulated:true. There is no override."
        )
    print(f"  backend: {body['cat']} (simulated)\n")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    base = sys.argv[1]
    require_simulator(base)

    failures = 0
    for path in READ:
        status, _ = get(base, path)
        if status != 200:
            print(f"  FAIL  {path}: {status}")
            failures += 1
    print(f"  read-only: {len(READ) - failures}/{len(READ)} answered 200")

    drive_fail = 0
    for path, field, expect in DRIVE:
        status, _ = get(base, path)
        if status != 200:
            print(f"  FAIL  {path}: {status}")
            drive_fail += 1
            continue
        # Wait for the value rather than sleeping a fixed guess: commands are
        # queued for the poller thread, so there is always some latency, and a
        # fixed sleep either flakes or wastes time. A bounded wait still fails
        # if the command never lands.
        src = "/api/status" if field in (
            "mode", "power", "split", "vfo", "vfo_locked", "diversity", "tx",
            "freq") else "/api/status/full"
        actual, waited = wait_for(base, src, field, expect)
        if actual != expect:
            print(f"  FAIL  {path}: {field} is {actual!r}, expected {expect!r}")
            drive_fail += 1
    print(f"  drive:     {len(DRIVE) - drive_fail}/{len(DRIVE)} verified by reading the rig back")

    smoke_fail = 0
    for path in SMOKE:
        status, _ = get(base, path)
        if status != 200:
            print(f"  FAIL  {path}: {status}")
            smoke_fail += 1
    print(f"  smoke:     {len(SMOKE) - smoke_fail}/{len(SMOKE)} answered 200")

    get(base, "/api/ptt/off")   # best effort; 404 today, see api.cpp
    total = failures + drive_fail + smoke_fail
    print(f"\n{total} failure(s)")
    return 1 if total else 0


if __name__ == "__main__":
    sys.exit(main())
