#!/usr/bin/env python3
"""Exercise EVERY implemented route, including the ones that key the transmitter.

    tools/walk_all_routes.py <host:port>

⚠️ THIS TOOL FIRES STATE-CHANGING ROUTES. It will key PTT, change mode, switch
antennas and move the frequency. Against a real station that is exactly the
accident CARRYOVER.md section 9 records - a control-route probe that changed the
operating mode mid-session.

So it refuses to run unless the target PROVES it is a simulator:

    GET /api/backend  ->  {"simulated": true}

The reference .NET host does not serve that route at all, so it 404s there and
this tool refuses. Anything that is not an explicit simulated:true is a refusal -
a 404, a connection error, a missing field. It fails CLOSED.

There is deliberately no --force. An override would make the check advisory, and
an advisory check on something that keys a transmitter is not a check.
"""

